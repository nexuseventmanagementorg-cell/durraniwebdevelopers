const previousProductsById = new Map(previousProducts.map((product) => [product.id, product]));

function menuProduct(
  id: string,
  nameEn: string,
  nameUr: string,
  categoryId: string,
  price: number,
  image: string,
  descriptionEn: string,
  originalMenuSection: string
): Product {
  const previous = previousProductsById.get(id);
  return {
    id,
    nameEn,
    nameUr,
    categoryId,
    price,
    descriptionEn,
    descriptionUr: previous?.descriptionUr ?? nameUr,
    image,
    isAvailable: previous?.isAvailable ?? true,
    isFeatured: previous?.isFeatured ?? false,
    originalPriceFormat: `${price}/- روپے`,
    verifiedFromMenu: true,
    originalMenuSection,
  };
}

